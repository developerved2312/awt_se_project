export const generateWeeklyTrend = (basePrice, variationPercent = 3) => {
  const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Today'];
  const daysGu = ['સોમ', 'મંગળ', 'બુધ', 'ગુરુ', 'શુક્ર', 'શનિ', 'આજે'];
  const today = new Date();

  return days.map((day, idx) => {
    const dayDate = new Date();
    dayDate.setDate(today.getDate() - (6 - idx));
    const factor = 1 + ((idx - 3) * 0.008) + ((Math.sin(idx * 1.5) * variationPercent) / 100);
    const modalPrice = Math.round((basePrice * factor) / 10) * 10;
    return {
      day,
      dayGu: daysGu[idx],
      date: dayDate.toISOString().split('T')[0],
      modalPrice,
    };
  });
};

